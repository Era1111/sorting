#include <iostream> // Ввод и вывод.
#include <vector> // Массивы переменной длины.
using namespace std;

int main() {
    int n; cin >> n; // Читаем размер массива.
    vector<long long> a(n); // Создаём массив из n чисел.
    for (auto &x : a) cin >> x; // Вводим числа по порядку.
    for (int i = 1; i < n; i++) {
        long long key = a[i]; // Сохраняем число для вставки.
        int j = i - 1; // Начинаем с левого соседа.
        while (j >= 0 && a[j] > key) {
            a[j + 1] = a[j]; // Сдвигаем большее число вправо.
            j--; // Проверяем следующего соседа слева.
        }
        a[j + 1] = key; // Заполняем свободную клетку.
        for (int i = 0; i < n; i++) {
            if (i > 0) cout << ' '; // Пробел между числами.
            cout << a[i]; // Печатаем очередное число.
        }
        cout << '\n';
    }
}
